"""Write research-paper/tables/example.tex: one development-split benchmark
question rendered from public-input.jsonl and private-gold.jsonl, so the
appendix example is the record itself and not a retyped copy.

    uv run python scripts/statutory-qa/make_benchmark_example.py --question M027-Q01
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sq_common as C  # noqa: E402

OUT = C.ROOT / "research-paper" / "tables" / "example.tex"

_ESC = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(s: str) -> str:
    s = "".join(_ESC.get(ch, ch) for ch in str(s))
    return s.replace('"', "''")


def clip(s: str, n: int) -> str:
    s = " ".join(str(s).split())
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--question", default="M027-Q01")
    ap.add_argument("--excerpt-chars", type=int, default=220)
    args = ap.parse_args(argv)

    dev = C.read_json(C.BENCHMARK_DIR / "development-ids.json")
    if args.question not in dev["questions"]:
        raise SystemExit(f"{args.question} is not in the development split; refusing to print a test question")
    pub = {r["benchmark_question_id"]: r for r in C.read_jsonl(C.BENCHMARK_DIR / "public-input.jsonl")}
    gold = {r["benchmark_question_id"]: r for r in C.read_jsonl(C.BENCHMARK_DIR / "private-gold.jsonl")}
    p, g = pub[args.question], gold[args.question]
    by_prov = {x["provision_id"]: x for x in g["indispensable_provisions"] + g.get("supporting_provisions", [])}

    L = []
    L.append("% generated by scripts/statutory-qa/make_benchmark_example.py; do not edit")
    L.append(r"\small")
    L.append(r"\paragraph{Public input.} " + f"Question {tex(args.question)}, paper {p['paper_no']}, "
             f"{tex(p['exam_session'].title())} sitting; reference date {tex(p['matter_reference_date'])}; "
             f"enrichment {'applied' if p['enriched'] else 'not applied'}.")
    L.append(r"\begin{quote}\small")
    L.append(r"\textit{Background.} " + tex(p["background"]))
    L.append("")
    L.append(r"\textit{Question.} " + tex(p["question"]))
    L.append(r"\end{quote}")

    L.append(r"\paragraph{Proposed gold (private view).} Authority requirement "
             f"\\textsc{{{tex(g['authority_requirement'].replace('_', ' '))}}}; legal hop count {g['legal_hop_count']}; "
             f"gold Acts {', '.join(tex(a) for a in g['gold_act_ids'])}; status \\textsc{{{tex(g['research_status'].replace('_', ' '))}}}, "
             f"lawyer validation \\textsc{{{tex(g['lawyer_validation_status'])}}}.")
    L.append(r"\begin{enumerate}\setlength{\itemsep}{0pt}")
    for iss in g["legal_issues"]:
        L.append(r"\item " + tex(iss["issue"]))
    L.append(r"\end{enumerate}")

    L.append(r"\begin{tabular}{@{}p{0.30\linewidth}p{0.66\linewidth}@{}}")
    L.append(r"\toprule Indispensable provision & Excerpt checked verbatim against the corpus \\ \midrule")
    for x in g["indispensable_provisions"]:
        sub = (x.get("subsection") or "").strip()
        if sub and not sub.startswith("("):
            sub = " " + sub
        cite = f"{tex(x['formal_title'])} {tex(x['number_and_year'])}, s.\\,{tex(x['section'])}{tex(sub)}"
        L.append(f"{cite} & {tex(clip(x['relevant_excerpt'], args.excerpt_chars))} \\\\")
    L.append(r"\bottomrule\end{tabular}")

    supp = g.get("supporting_section_ids") or []
    if supp:
        L.append("")
        L.append(r"\noindent Supporting (not scored): " + ", ".join(tex(s) for s in supp) + ".")

    edges = g.get("reasoning_edges") or []
    if edges:
        def sid(pid):
            x = by_prov.get(pid)
            return tex(x["section_id"]) if x else tex(pid)
        # one row per relationship type; edges deduplicated, first-appearance order kept
        grouped: dict[str, list[str]] = {}
        for e in edges:
            src, dst = sid(e["from_provision_id"]), sid(e["to_provision_id"])
            if src == dst:  # provisions of one section collapse to a self-loop at section level
                continue
            pair = f"{src} $\\to$ {dst}"
            rows = grouped.setdefault(e["relationship"], [])
            if pair not in rows:
                rows.append(pair)
        L.append("")
        L.append(r"\noindent Reasoning edges (source $\to$ target):")
        L.append("")
        L.append(r"\noindent\begin{tabular}{@{}lp{0.74\linewidth}@{}}")
        for rel, rows in grouped.items():
            label = tex(rel.replace("_", " ").lower())
            L.append(f"\\textsc{{{label}}} & {'; '.join(rows)} \\\\")
        L.append(r"\end{tabular}")

    a = g["gold_answer_draft"]
    L.append(r"\paragraph{Draft answer (agent-written, unvalidated).}")
    for k in ("issue", "rule", "application", "conclusion"):
        if a.get(k):
            L.append(r"\textit{" + k.title() + ".} " + tex(a[k]))
            L.append("")

    claims = g.get("answer_claims") or []
    if claims:
        L.append(r"\noindent Claim-level provenance, first two of " + str(len(claims)) + ":")
        L.append(r"\begin{itemize}\setlength{\itemsep}{0pt}")
        for c in claims[:2]:
            provs = ", ".join(tex(by_prov[pid]["section_id"]) if pid in by_prov else tex(pid) for pid in c["supporting_provision_ids"])
            L.append(r"\item [" + tex(c["claim_type"]) + "] " + tex(c["claim_text"]) + f" \\hfill $\\leftarrow$ {provs}")
        L.append(r"\end{itemize}")

    C.write_text(OUT, "\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(C.ROOT)} for {args.question}: {len(g['indispensable_provisions'])} indispensable, {len(claims)} claims")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
